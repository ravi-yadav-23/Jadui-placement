import random

import pytest

from app.resume.pipeline.guard import NUMBER, guard_rewrite
from app.resume.pipeline.lint import lint_bullet, lint_resume, unsupported_skills
from app.resume.schemas import ResumeProfile

# ---------- lint ----------


@pytest.mark.parametrize(("bullet", "expected"), [
    ("Built a FastAPI service for invoice reconciliation handling 20k requests per day", []),
    ("Responsible for writing unit tests with pytest for the billing service", ["no_metric", "weak_start"]),
    ("Optimized slow SQL queries and caching so dashboards loaded faster for staff", ["no_metric"]),
    ("I built a dashboard that my team used to track 300 student placements daily", ["weak_start", "pronoun"]),
    ("Reports were generated by the system for 40 schools across the district weekly", ["weak_start", "passive"]),
    ("Built APIs", ["no_metric", "length"]),
    ("Passionate engineer who developed various tools for 5 internal teams at the firm", ["weak_start", "buzzword",
                                                                                          "vague"]),
])
def test_lint_bullet(bullet, expected):
    assert lint_bullet(bullet) == expected


def profile_with(bullets: list[str], skills: list[str], tech: list[str] | None = None) -> ResumeProfile:
    return ResumeProfile.model_validate({
        "skills": skills,
        "projects": [{"id": "proj0", "title": "Tracker", "tech": tech or [],
                      "bullets": [{"id": f"proj0.b{i}", "text": t} for i, t in enumerate(bullets)]}],
    })


def test_unsupported_skills_are_technologies_never_shown_anywhere():
    profile = profile_with(["Built a FastAPI backend for 300 students"], ["Python", "FastAPI", "Kubernetes",
                                                                           "Teamwork", "DSA"], tech=["Python"])
    assert unsupported_skills(profile) == ["Kubernetes"]  # Teamwork/DSA are not technologies


def test_implied_skills_count_as_evidence():
    profile = profile_with(["Developed a Next.js dashboard backed by FastAPI for 300 students"],
                           ["Python", "React", "JavaScript", "Docker"])
    assert unsupported_skills(profile) == ["Docker"]  # FastAPI -> Python, Next.js -> React -> JavaScript


def test_repeated_opening_verb_is_reported():
    profile = profile_with([f"Built feature number {i} for the admissions portal team" for i in range(4)], [])
    assert [f.code for f in lint_resume(profile)] == ["repeated_verb"]


# ---------- truth guard ----------

ORIGINAL = "Built a FastAPI service for invoice reconciliation handling 20k requests per day"


def test_rewrite_that_only_rephrases_is_kept():
    result = guard_rewrite(ORIGINAL, "Engineered a FastAPI reconciliation service processing 20k invoices daily")
    assert result.text == "Engineered a FastAPI reconciliation service processing 20k invoices daily"
    assert result.notes == []


def test_invented_numbers_become_placeholders():
    result = guard_rewrite(ORIGINAL, "Built a FastAPI service handling 20k requests/day with 99.9% uptime")
    assert result.text == "Built a FastAPI service handling 20k requests/day with [X]% uptime"
    assert result.notes


def test_added_technology_is_rejected_unless_in_the_entry_stack():
    rewrite = "Built a FastAPI and Redis service handling 20k requests per day"
    assert guard_rewrite(ORIGINAL, rewrite).text is None
    assert guard_rewrite(ORIGINAL, rewrite, allowed_tech={"Redis"}).text == rewrite


def test_added_company_name_is_rejected():
    assert guard_rewrite(ORIGINAL, "Built a FastAPI service for Stripe handling 20k requests per day").text is None


def test_added_leadership_is_rejected():
    assert guard_rewrite(ORIGINAL, "Led a FastAPI service build handling 20k requests per day").text is None


def test_property_no_new_number_ever_survives():
    """Random rewrites full of numbers: every surviving number must come from the original."""
    rng = random.Random(7)
    original_numbers = {"20"}
    for _ in range(300):
        words = ["Built", "a", "service", "handling", "20k", "requests"] + \
                [str(rng.randint(0, 5000)) + rng.choice(["", "%", "k", "x"]) for _ in range(rng.randint(1, 4))]
        rng.shuffle(words[1:])
        result = guard_rewrite(ORIGINAL, " ".join(words))
        if result.text:
            assert {n.replace(",", "") for n in NUMBER.findall(result.text)} <= original_numbers
